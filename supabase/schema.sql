-- Les clients ne doivent jamais recevoir cette clé ni une policy publique.


-- Catalogue des produits géré depuis l'espace propriétaire.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Maison',
  price numeric(14,2) not null default 0 check (price >= 0),
  description text not null default '',
  image text not null default '',
  tag text not null default '',
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;
grant select on public.products to anon, authenticated;
drop policy if exists "Published products are publicly readable" on public.products;
create policy "Published products are publicly readable"
  on public.products for select to anon, authenticated
  using (published = true);

